// Runtime packs: separately installed runtimes that sidecar models need. A pack
// is installed under userData/runtimes/<id>/ and never shares a folder with
// model weights. Tool and interpreter packs are pinned archives; sidecar packs
// are built on this machine from a pinned recipe (see runtimes.json).
const fs = require('node:fs');
const fsp = fs.promises;
const path = require('node:path');
const crypto = require('node:crypto');
const { spawn } = require('node:child_process');
const { extractArchive } = require('./archive.cjs');
const { getModel } = require('./registry.cjs');
const { probeNvidia } = require('./hardware.cjs');

const MARKER = '.voxarium-runtime.json';
const STATE_VERSION = 1;
const MAX_REDIRECTS = 5;
const TORCH_INDEX = 'https://download.pytorch.org/whl';
// Microsoft's redistributable DLLs, installed into every environment. The newest
// release has no CPython 3.11 wheel, so 3.11 environments get the previous one.
const MSVC_RUNTIME = ['msvc-runtime==14.51.36231; python_version >= "3.12"', 'msvc-runtime==14.44.35112; python_version < "3.12"'];
const BUILD_LOG_LIMIT = 400;

/** Bundled sidecar server, adapters, shims and assets (unpacked next to app.asar in builds). */
function sidecarAppDir() {
  const bundled = path.join(__dirname, '..', 'sidecars');
  const unpacked = bundled.replace(`${path.sep}app.asar${path.sep}`, `${path.sep}app.asar.unpacked${path.sep}`);
  return unpacked !== bundled && fs.existsSync(unpacked) ? unpacked : bundled;
}

/**
 * uv builds source-only packages inside its cache, and setuptools on Windows
 * fails past 260 characters unless long paths are enabled system-wide. Keep the
 * cache next to the runtimes when that path is short; otherwise use a short
 * folder at the root of the same drive (hard links need the same volume).
 */
function uvCacheDir(runtimesDir) {
  if (process.env.VOXARIUM_UV_CACHE) return process.env.VOXARIUM_UV_CACHE;
  const preferred = path.join(runtimesDir, '.uv-cache');
  if (process.platform !== 'win32' || preferred.length <= 64) return preferred;
  const short = path.join(path.parse(path.resolve(runtimesDir)).root, 'VoxariumCache', 'uv');
  try {
    fs.mkdirSync(short, { recursive: true });
    return short;
  } catch {
    return preferred;
  }
}

function startScript(pack) {
  const sources = (pack.build.sources || []).map((source) => source.name);
  const shims = (pack.build.shims || []).length ? ['shims'] : [];
  const extra = [...sources.map((name) => `os.path.join(HERE, "src", ${JSON.stringify(name)})`), ...shims.map((name) => `os.path.join(HERE, "app", ${JSON.stringify(name)})`)];
  return [
    '# Generated by Voxarium. Starts the loopback server for this runtime pack.',
    'import os',
    'import sys',
    '',
    'HERE = os.path.dirname(os.path.abspath(__file__))',
    `sys.path[:0] = [os.path.join(HERE, "app")${extra.length ? `, ${extra.join(', ')}` : ''}]`,
    '',
    '# The Visual C++ runtime ships inside the environment (msvc-runtime), so machines',
    '# without the system redistributable can still load ONNX Runtime and PyTorch.',
    'for _dll_dir in (sys.prefix, os.path.join(sys.prefix, "Scripts")):',
    '    if os.path.isdir(_dll_dir):',
    '        os.add_dll_directory(_dll_dir)',
    '        os.environ["PATH"] = _dll_dir + os.pathsep + os.environ.get("PATH", "")',
    '',
    'from voxarium_sidecar import main',
    '',
    'if __name__ == "__main__":',
    `    main(${JSON.stringify(pack.build.adapter)})`,
    '',
  ].join('\n');
}

function sizeOf(filePath) {
  try {
    return fs.statSync(filePath).size;
  } catch {
    return 0;
  }
}

function sha256File(filePath) {
  return new Promise((resolve, reject) => {
    const hash = crypto.createHash('sha256');
    const stream = fs.createReadStream(filePath);
    stream.on('error', reject);
    stream.on('data', (chunk) => hash.update(chunk));
    stream.on('end', () => resolve(hash.digest('hex')));
  });
}

async function moveAtomic(from, to) {
  await fsp.mkdir(path.dirname(to), { recursive: true });
  try {
    await fsp.rename(from, to);
  } catch (error) {
    if (error && (error.code === 'EXDEV' || error.code === 'EPERM' || error.code === 'EACCES')) {
      await fsp.cp(from, to, { recursive: true, force: true });
      await fsp.rm(from, { recursive: true, force: true });
      return;
    }
    throw error;
  }
}

function loadCatalog() {
  const file = path.join(__dirname, 'runtimes.json');
  const parsed = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (!parsed || !Array.isArray(parsed.packs)) throw new Error('runtimes.json is malformed');
  const byId = new Map(parsed.packs.map((pack) => [pack.id, pack]));
  return { document: parsed, packs: parsed.packs, byId };
}

let catalog = null;
function getCatalog() {
  if (!catalog) catalog = loadCatalog();
  return catalog;
}

function getPack(id) {
  return getCatalog().byId.get(id) || null;
}

function runtimeDir(dirs, id) {
  return path.join(dirs.runtimes, id);
}

function stagingDir(dirs, id) {
  return path.join(dirs.runtimes, '.staging', id);
}

function entryNames(pack) {
  return Object.values(pack.entry || {}).filter((name) => typeof name === 'string' && name);
}

function entryReady(root, pack) {
  const names = entryNames(pack);
  if (!names.length) return false;
  return names.every((name) => {
    try {
      return fs.statSync(path.join(root, name)).isFile();
    } catch {
      return false;
    }
  });
}

function createRuntimeManager({
  dirs,
  appVersion,
  readJson,
  writeJsonAtomic,
  broadcast,
  log = console.log,
}) {
  const stateFile = () => path.join(dirs.data || dirs.runtimes, 'runtimes-state.json');
  let activeDownload = null;

  const emit = (payload) => {
    try {
      broadcast?.(payload);
    } catch {}
  };

  const defaultRead = (file, fallback) => {
    try {
      return JSON.parse(fs.readFileSync(file, 'utf8'));
    } catch {
      return fallback;
    }
  };
  const defaultWrite = async (file, value) => {
    await fsp.mkdir(path.dirname(file), { recursive: true });
    const temp = `${file}.${process.pid}.tmp`;
    await fsp.writeFile(temp, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
    await fsp.rename(temp, file);
  };
  const readStateFile = readJson || defaultRead;
  const writeStateFile = writeJsonAtomic || defaultWrite;

  function readState() {
    const raw = readStateFile(stateFile(), null);
    const state = {
      version: STATE_VERSION,
      installs: {},
      ...(raw && typeof raw === 'object' ? raw : {}),
    };
    if (!state.installs || typeof state.installs !== 'object') state.installs = {};
    return state;
  }

  async function writeState(patch) {
    const next = { ...readState(), ...patch, version: STATE_VERSION, updatedAt: Date.now() };
    await writeStateFile(stateFile(), next);
    return next;
  }

  async function recordInstall(packId, patch) {
    const state = readState();
    state.installs[packId] = {
      installedAt: Date.now(),
      source: 'download',
      verifiedAt: Date.now(),
      ...(state.installs[packId] || {}),
      ...patch,
    };
    return writeState({ installs: state.installs });
  }

  async function clearInstall(packId) {
    const state = readState();
    delete state.installs[packId];
    return writeState({ installs: state.installs });
  }

  function readMarker(packId) {
    return readStateFile(path.join(runtimeDir(dirs, packId), MARKER), null);
  }

  function status(packId) {
    const pack = getPack(packId);
    if (!pack) return null;
    const root = runtimeDir(dirs, pack.id);
    const marker = readMarker(pack.id);
    const hasEntry = entryReady(root, pack);
    const installed = Boolean(marker && marker.id === pack.id && hasEntry);
    const record = readState().installs[pack.id] || {};
    return {
      id: pack.id,
      name: pack.name,
      kind: pack.kind,
      version: pack.version,
      platform: pack.platform,
      arch: pack.arch,
      description: pack.description,
      homepage: pack.homepage,
      license: pack.license,
      available: Boolean(pack.available),
      importable: pack.importable !== false,
      reason: pack.reason || null,
      entry: pack.entry || {},
      requires: pack.requires || [],
      provides: pack.provides || [],
      archive: pack.archive || null,
      buildable: Boolean(pack.build),
      variant: installed ? marker?.variant || null : null,
      sizeBytes: Number(pack.sizeBytes || pack.archive?.size || 0),
      installedBytes: Number(pack.installedBytes || 0),
      lifecycle: installed ? 'installed' : pack.available ? 'not-installed' : 'not-published',
      installed,
      bytes: installed ? Number(record.installedBytes || pack.installedBytes || 0) : 0,
      installedAt: installed ? record.installedAt || marker?.installedAt || null : null,
      verifiedAt: installed ? record.verifiedAt || marker?.verifiedAt || null : null,
      source: installed ? record.source || marker?.source || null : null,
      error: activeDownload?.packId === pack.id ? undefined : record.error || (marker && !hasEntry ? 'The installed pack is missing its entry point.' : undefined),
    };
  }

  function statusAll() {
    return getCatalog().packs.map((pack) => status(pack.id));
  }

  function modelRuntime(model) {
    const declared = model.runtimePack || {};
    if (declared.available) return { ready: true, available: true, packId: null, reason: null };
    const pack = declared.packId ? getPack(declared.packId) : null;
    if (!pack) {
      return {
        ready: false,
        available: false,
        packId: declared.packId || null,
        reason: declared.reason || 'This model has no published runtime pack yet.',
      };
    }
    const packStatus = status(pack.id);
    return {
      ready: Boolean(packStatus?.installed),
      available: Boolean(pack.available || packStatus?.installed),
      packId: pack.id,
      reason: packStatus?.installed ? null : pack.reason || declared.reason || `${pack.name} is not installed.`,
    };
  }

  function resolvePython(pack) {
    if (!pack) return null;
    const installed = status(pack.id);
    if (!installed?.installed) return null;
    const relative = pack.entry?.python;
    if (!relative) return null;
    const file = path.join(runtimeDir(dirs, pack.id), relative);
    return fs.existsSync(file) ? file : null;
  }

  function pythonFor(packId) {
    const pack = getPack(packId);
    if (!pack) return null;
    // Built sidecar packs carry their own virtual environment.
    if (pack.kind === 'python' || pack.entry?.python) return resolvePython(pack);
    const base = (pack.requires || []).map(getPack).find((item) => item && item.kind === 'python');
    return resolvePython(base || null);
  }

  function sidecarRuntime(model) {
    const declared = model.runtimePack || {};
    const pack = declared.packId ? getPack(declared.packId) : null;
    if (!pack) {
      return { ok: false, reason: declared.reason || 'This sidecar has no published runtime pack yet.' };
    }
    const installed = status(pack.id);
    if (!installed?.installed) {
      return { ok: false, reason: pack.reason || `${pack.name} is not installed. Download or import it first.` };
    }
    const python = pythonFor(pack.id);
    if (!python) {
      return {
        ok: false,
        reason: `${pack.name} has no Python environment. Reinstall the runtime from the Models page.`,
      };
    }
    const server = pack.entry?.server ? path.join(runtimeDir(dirs, pack.id), pack.entry.server) : null;
    return {
      ok: true,
      pack,
      python,
      server: server && fs.existsSync(server) ? server : null,
      root: runtimeDir(dirs, pack.id),
      reason: null,
    };
  }

  function sourceUrl(archive) {
    return archive.url;
  }

  async function fetchWithRedirects(url, options) {
    let current = url;
    for (let attempt = 0; attempt <= MAX_REDIRECTS; attempt += 1) {
      const response = await fetch(current, { ...options, redirect: 'manual' });
      if (response.status >= 300 && response.status < 400) {
        const location = response.headers.get('location');
        if (!location) throw new Error(`Download redirect had no location (${response.status}).`);
        current = new URL(location, current).toString();
        continue;
      }
      return response;
    }
    throw new Error('Too many download redirects.');
  }

  async function downloadArchive(pack, signal, index, count, archive = pack.archive) {
    const stage = stagingDir(dirs, pack.id);
    const partPath = path.join(stage, `${archive.name}.part`);
    const finalPath = path.join(stage, archive.name);
    await fsp.mkdir(stage, { recursive: true });

    if (fs.existsSync(finalPath) && sizeOf(finalPath) === archive.size) {
      emit({ kind: 'runtime', runtimeId: pack.id, file: archive.name, loaded: archive.size, total: archive.size, percent: 100, index, count, stage: 'verifying', cached: true, at: Date.now() });
      const hash = await sha256File(finalPath);
      if (hash === archive.sha256) return finalPath;
      await fsp.rm(finalPath, { force: true });
    }

    const headers = { 'user-agent': `Voxarium/${appVersion || '1.0.0'}` };
    for (let attempt = 0; attempt < 2; attempt += 1) {
      let offset = sizeOf(partPath);
      if (offset > archive.size) {
        await fsp.rm(partPath, { force: true });
        offset = 0;
      }
      if (offset === archive.size) {
        const hash = await sha256File(partPath);
        if (hash === archive.sha256) {
          await moveAtomic(partPath, finalPath);
          return finalPath;
        }
        await fsp.rm(partPath, { force: true });
        offset = 0;
      }

      emit({ kind: 'runtime', runtimeId: pack.id, file: archive.name, loaded: offset, total: archive.size, percent: archive.size ? (offset / archive.size) * 100 : null, index, count, stage: 'downloading', at: Date.now() });
      const response = await fetchWithRedirects(sourceUrl(archive), {
        headers: { ...headers, ...(offset > 0 ? { range: `bytes=${offset}-` } : {}) },
        signal,
      });
      if (!response.ok || !response.body) {
        if (response.status === 401 || response.status === 403) {
          throw new Error(`${pack.name} could not be downloaded (HTTP ${response.status}). The pack may be private or rate-limited.`);
        }
        throw new Error(`Download failed (${response.status} ${response.statusText}) for ${archive.name}`);
      }
      const isRange = response.status === 206;
      if (!isRange) offset = 0;
      const handle = await fsp.open(partPath, isRange && offset > 0 ? 'a' : 'w');
      let loaded = offset;
      let lastEmit = 0;
      try {
        const reader = response.body.getReader();
        for (;;) {
          const chunk = await reader.read();
          if (chunk.done) break;
          if (signal?.aborted) throw Object.assign(new Error('Download cancelled'), { name: 'AbortError' });
          await handle.write(chunk.value);
          loaded += chunk.value.byteLength;
          const now = Date.now();
          if (now - lastEmit > 120) {
            lastEmit = now;
            emit({ kind: 'runtime', runtimeId: pack.id, file: archive.name, loaded, total: archive.size, percent: archive.size ? Math.min(100, (loaded / archive.size) * 100) : null, index, count, stage: 'downloading', at: now });
          }
        }
      } finally {
        await handle.close().catch(() => {});
      }

      const actual = sizeOf(partPath);
      if (actual !== archive.size) {
        log(`[voxarium] ${pack.id} archive incomplete (${actual}/${archive.size}); retrying`);
        continue;
      }
      emit({ kind: 'runtime', runtimeId: pack.id, file: archive.name, loaded: actual, total: archive.size, percent: 100, index, count, stage: 'verifying', at: Date.now() });
      const hash = await sha256File(partPath);
      if (hash !== archive.sha256) {
        await fsp.rm(partPath, { force: true });
        continue;
      }
      await moveAtomic(partPath, finalPath);
      return finalPath;
    }
    throw new Error(`${pack.name} failed SHA-256 verification twice. The download may be corrupted or the pack changed.`);
  }

  /** Writes the marker into a finished tree and swaps it into runtimes/<id> atomically. */
  async function swapIntoPlace(pack, tree, marker) {
    if (!entryReady(tree, pack)) {
      throw new Error(`${pack.name} did not contain its expected entry point (${entryNames(pack).join(', ')}).`);
    }
    await fsp.writeFile(path.join(tree, MARKER), `${JSON.stringify(marker, null, 2)}\n`, 'utf8');
    const target = runtimeDir(dirs, pack.id);
    const backup = `${target}.old-${Date.now()}`;
    await fsp.mkdir(path.dirname(target), { recursive: true });
    if (fs.existsSync(target)) {
      try {
        await fsp.rename(target, backup);
      } catch {
        await fsp.rm(target, { recursive: true, force: true });
      }
    }
    try {
      await moveAtomic(tree, target);
    } catch (error) {
      if (fs.existsSync(backup)) await fsp.rename(backup, target).catch(() => {});
      throw error;
    }
    await fsp.rm(backup, { recursive: true, force: true }).catch(() => {});
    await fsp.rm(stagingDir(dirs, pack.id), { recursive: true, force: true }).catch(() => {});
    return target;
  }

  async function installArchive(pack, archivePath) {
    const extractDir = path.join(stagingDir(dirs, pack.id), 'extract');
    await fsp.rm(extractDir, { recursive: true, force: true });
    await fsp.mkdir(extractDir, { recursive: true });
    await extractArchive(archivePath, extractDir);
    return swapIntoPlace(pack, extractDir, {
      id: pack.id,
      version: pack.version,
      archive: pack.archive ? { name: pack.archive.name, size: pack.archive.size, sha256: pack.archive.sha256 } : null,
      entry: pack.entry,
      source: 'download',
      installedAt: Date.now(),
      verifiedAt: Date.now(),
    });
  }

  // ---------------------------------------------------------------------------
  // Recipe builds: an isolated venv per sidecar, created by the pinned uv.
  // ---------------------------------------------------------------------------

  // Minimum NVIDIA driver (major version) for each CUDA build of PyTorch on Windows.
  const CUDA_MIN_DRIVER = { cu126: 560, cu128: 570, cu129: 575, cu130: 580 };
  let nvidiaCache = null;
  async function torchVariant(pack) {
    const torch = pack.build?.torch;
    if (!torch) return 'none';
    if (process.env.VOXARIUM_TORCH_VARIANT === 'cpu') return 'cpu';
    if (nvidiaCache == null) nvidiaCache = await probeNvidia().catch(() => []);
    const driver = Math.max(0, ...nvidiaCache.map((gpu) => Number.parseInt(gpu.driver, 10) || 0));
    if (!nvidiaCache.length) return 'cpu';
    // An older driver cannot load this CUDA build; the CPU wheels still run.
    if (driver < (CUDA_MIN_DRIVER[torch.cuda] || 0)) {
      log(`[voxarium] NVIDIA driver ${driver} is older than ${torch.cuda} needs; using CPU PyTorch for ${pack.id}.`);
      return 'cpu';
    }
    return torch.cuda;
  }

  function uvExe() {
    const uv = getPack('uv-win-x64');
    if (!uv || !status(uv.id)?.installed) return null;
    return path.join(runtimeDir(dirs, uv.id), uv.entry.uv);
  }

  function runLogged(command, args, { cwd, env, signal, onLine }) {
    return new Promise((resolve, reject) => {
      const child = spawn(command, args, { cwd, env, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
      const tail = [];
      let buffer = '';
      const onData = (chunk) => {
        const text = buffer + chunk.toString('utf8');
        const lines = text.split(/\r?\n|\r/);
        buffer = lines.pop() || '';
        for (const raw of lines) {
          const line = raw.trimEnd();
          if (!line) continue;
          tail.push(line);
          if (tail.length > BUILD_LOG_LIMIT) tail.shift();
          onLine?.(line);
        }
      };
      child.stdout.on('data', onData);
      child.stderr.on('data', onData);
      const abort = () => child.kill();
      signal?.addEventListener('abort', abort, { once: true });
      child.on('error', (error) => {
        signal?.removeEventListener('abort', abort);
        reject(error);
      });
      child.on('close', (code) => {
        signal?.removeEventListener('abort', abort);
        if (buffer.trim()) tail.push(buffer.trim());
        if (signal?.aborted) return reject(Object.assign(new Error('Install cancelled'), { name: 'AbortError' }));
        if (code === 0) return resolve(tail);
        const detail = tail.filter((line) => /error|failed|because|no solution|not found|requires/i.test(line)).slice(-6).join('\n') || tail.slice(-8).join('\n');
        reject(Object.assign(new Error(`${path.basename(command)} exited with code ${code}.\n${detail}`), { log: tail }));
      });
    });
  }

  async function buildPack(pack, signal) {
    const build = pack.build;
    const uv = uvExe();
    if (!uv) throw new Error('The uv package manager is not installed.');
    const stage = stagingDir(dirs, pack.id);
    const tree = path.join(stage, 'tree');
    await fsp.rm(tree, { recursive: true, force: true });
    await fsp.mkdir(tree, { recursive: true });

    const variant = await torchVariant(pack);
    const steps = 4 + (build.sources || []).length;
    let step = 0;
    const progress = (label, extra = {}) =>
      emit({ kind: 'runtime', runtimeId: pack.id, file: label, loaded: step, total: steps, percent: (step / steps) * 100, index: step, count: steps, stage: 'installing', at: Date.now(), ...extra });

    const env = {
      ...process.env,
      UV_CACHE_DIR: uvCacheDir(dirs.runtimes),
      UV_PYTHON_INSTALL_DIR: path.join(dirs.runtimes, '.uv-python'),
      UV_LINK_MODE: 'hardlink',
      UV_NO_CONFIG: '1',
      UV_HTTP_TIMEOUT: '600',
      UV_NO_PROGRESS: '1',
      PYTHONNOUSERSITE: '1',
      PIP_DISABLE_PIP_VERSION_CHECK: '1',
      VIRTUAL_ENV: '',
    };

    // 1. Interpreter + virtual environment.
    progress(`Creating a Python ${build.python} environment`);
    const pythonPack = (pack.requires || []).map(getPack).find((item) => item?.kind === 'python');
    const basePython = build.python === pythonPack?.version.split('.').slice(0, 2).join('.') ? resolvePython(pythonPack) : null;
    const venv = path.join(tree, 'venv');
    const venvArgs = ['venv', venv, '--relocatable', '--python', basePython || build.python];
    if (!basePython) venvArgs.push('--python-preference', 'only-managed');
    await runLogged(uv, venvArgs, { env, signal, onLine: (line) => progress(line) });
    const venvPython = path.join(venv, 'Scripts', 'python.exe');
    step += 1;

    // 2. Requirements. PyTorch comes from the matching PyTorch index (CUDA build on NVIDIA GPUs).
    const requirements = [];
    const installArgs = ['pip', 'install', '--python', venvPython, '--link-mode', 'hardlink'];
    if (build.torch) {
      for (const [name, version] of Object.entries(build.torch.packages)) requirements.push(`${name}==${version}+${variant}`);
      installArgs.push('--extra-index-url', `${TORCH_INDEX}/${variant}`, '--index-strategy', 'unsafe-best-match');
    }
    requirements.push(...build.requirements, ...MSVC_RUNTIME);
    await fsp.writeFile(path.join(tree, 'requirements.txt'), `${requirements.join('\n')}\n`, 'utf8');
    installArgs.push('-r', path.join(tree, 'requirements.txt'));
    if (build.overrides?.length) {
      await fsp.writeFile(path.join(tree, 'overrides.txt'), `${build.overrides.join('\n')}\n`, 'utf8');
      installArgs.push('--override', path.join(tree, 'overrides.txt'));
    }
    progress(build.torch ? `Installing packages (PyTorch ${build.torch.packages.torch}, ${variant === 'cpu' ? 'CPU' : variant.toUpperCase()})` : 'Installing packages');
    await runLogged(uv, installArgs, { env, signal, onLine: (line) => progress(line) });
    step += 1;

    // 3. Pinned source trees that are run from disk rather than installed.
    for (const source of build.sources || []) {
      progress(`Downloading ${source.name} source`);
      const archive = { name: `${source.name}.zip`, url: source.url, size: source.size, sha256: source.sha256 };
      const archivePath = await downloadArchive(pack, signal, step, steps, archive);
      const extractDir = path.join(stage, `src-${source.name}`);
      await fsp.rm(extractDir, { recursive: true, force: true });
      await extractArchive(archivePath, extractDir);
      const entries = await fsp.readdir(extractDir, { withFileTypes: true });
      const root = entries.length === 1 && entries[0].isDirectory() ? path.join(extractDir, entries[0].name) : extractDir;
      await fsp.mkdir(path.join(tree, 'src'), { recursive: true });
      await moveAtomic(root, path.join(tree, 'src', source.name));
      await fsp.rm(extractDir, { recursive: true, force: true }).catch(() => {});
      step += 1;
    }

    // 4. Voxarium's adapter, shims and assets, then the start script.
    progress('Installing the Voxarium adapter');
    const appSource = sidecarAppDir();
    const app = path.join(tree, 'app');
    await fsp.mkdir(path.join(app, 'adapters'), { recursive: true });
    await fsp.copyFile(path.join(appSource, 'voxarium_sidecar.py'), path.join(app, 'voxarium_sidecar.py'));
    await fsp.copyFile(path.join(appSource, 'adapters', '__init__.py'), path.join(app, 'adapters', '__init__.py'));
    await fsp.copyFile(path.join(appSource, 'adapters', `${build.adapter}.py`), path.join(app, 'adapters', `${build.adapter}.py`));
    await fsp.cp(path.join(appSource, 'assets'), path.join(app, 'assets'), { recursive: true });
    for (const shim of build.shims || []) {
      await fsp.cp(path.join(appSource, 'shims', shim), path.join(app, 'shims', shim), { recursive: true });
    }
    await fsp.writeFile(path.join(tree, 'start.py'), startScript(pack), 'utf8');
    step += 1;

    // 5. Import check: proves the environment can load the adapter's dependencies.
    progress('Checking the environment');
    const checked = await runLogged(venvPython, ['-I', path.join(tree, 'start.py'), '--check', '--model-dir', tree], {
      cwd: tree,
      env: { ...env, PYTHONIOENCODING: 'utf-8', PYTHONUTF8: '1' },
      signal,
    });
    if (!checked.some((line) => line.includes('VOXARIUM_CHECK_OK'))) {
      throw new Error(`${pack.name} installed, but its adapter could not import its dependencies.\n${checked.slice(-8).join('\n')}`);
    }
    step += 1;

    return swapIntoPlace(pack, tree, {
      id: pack.id,
      version: pack.version,
      archive: null,
      entry: pack.entry,
      source: 'build',
      variant,
      requirements,
      installedAt: Date.now(),
      verifiedAt: Date.now(),
    });
  }

  /** Installs one pack (download or build) without touching its prerequisites. */
  async function installOne(pack, signal) {
    if (pack.build) {
      await buildPack(pack, signal);
      await recordInstall(pack.id, { source: 'build', installedBytes: pack.installedBytes || 0, archive: null, error: null });
    } else {
      const archivePath = await downloadArchive(pack, signal, 0, 1);
      emit({ kind: 'runtime', runtimeId: pack.id, file: pack.archive.name, loaded: pack.archive.size, total: pack.archive.size, percent: 100, index: 0, count: 1, stage: 'installing', at: Date.now() });
      await installArchive(pack, archivePath);
      await recordInstall(pack.id, {
        source: 'download',
        installedBytes: pack.installedBytes || 0,
        archive: { name: pack.archive.name, size: pack.archive.size, sha256: pack.archive.sha256 },
        error: null,
      });
    }
    emit({ kind: 'runtime', runtimeId: pack.id, file: '', loaded: 1, total: 1, percent: 100, index: 1, count: 1, stage: 'installed', done: true, at: Date.now() });
  }

  function installPlan(pack, seen = new Set()) {
    if (seen.has(pack.id)) return [];
    seen.add(pack.id);
    const plan = [];
    for (const id of pack.requires || []) {
      const dependency = getPack(id);
      if (!dependency) throw new Error(`${pack.name} requires an unknown runtime (${id}).`);
      plan.push(...installPlan(dependency, seen));
    }
    plan.push(pack);
    return plan;
  }

  /** Installs a pack and every prerequisite that is missing (uv, the interpreter, then the pack). */
  async function download(packId, { force = false } = {}) {
    if (activeDownload) return { ok: false, error: 'Another runtime install is already running.' };
    const pack = getPack(packId);
    if (!pack) return { ok: false, error: 'Unknown runtime pack.' };
    if (!pack.available || (!pack.archive && !pack.build)) {
      return { ok: false, error: pack.reason || `${pack.name} has not been published for download yet.` };
    }
    const controller = new AbortController();
    activeDownload = { controller, packId: pack.id };
    let current = pack;
    try {
      const plan = installPlan(pack).filter((item) => (item.id === pack.id ? force || !status(item.id)?.installed : !status(item.id)?.installed));
      for (const item of plan) {
        current = item;
        activeDownload.packId = item.id;
        await installOne(item, controller.signal);
      }
      return { ok: true, status: status(pack.id) };
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      const aborted = controller.signal.aborted || (error && error.name === 'AbortError');
      if (!aborted) await recordInstall(current.id, { error: message }).catch(() => {});
      log(`[voxarium] runtime ${current.id} failed: ${message}`);
      emit({ kind: 'runtime', runtimeId: current.id, file: '', loaded: 0, total: 0, percent: null, index: 0, count: 0, stage: 'error', error: aborted ? 'Install cancelled' : message, done: true, at: Date.now() });
      if (current.id !== pack.id) {
        emit({ kind: 'runtime', runtimeId: pack.id, file: '', loaded: 0, total: 0, percent: null, index: 0, count: 0, stage: 'error', error: aborted ? 'Install cancelled' : `${current.name}: ${message}`, done: true, at: Date.now() });
      }
      return { ok: false, error: aborted ? 'Install cancelled' : current.id === pack.id ? message : `${current.name} could not be installed: ${message}` };
    } finally {
      activeDownload = null;
    }
  }

  async function cancel() {
    activeDownload?.controller.abort();
    return true;
  }

  async function verify(packId) {
    const pack = getPack(packId);
    if (!pack) return { ok: false, error: 'Unknown runtime pack.' };
    const root = runtimeDir(dirs, pack.id);
    const marker = readMarker(pack.id);
    if (!marker) return { ok: false, error: `${pack.name} is not installed.` };
    if (!entryReady(root, pack)) return { ok: false, error: `${pack.name} is missing its entry point. Reinstall or import it again.` };
    const verifiedAt = Date.now();
    const nextMarker = { ...marker, verifiedAt };
    await fsp.writeFile(path.join(root, MARKER), `${JSON.stringify(nextMarker, null, 2)}\n`, 'utf8');
    await recordInstall(pack.id, { verifiedAt, error: null, installedBytes: pack.installedBytes || marker.installedBytes || 0 });
    return { ok: true, status: status(pack.id) };
  }

  async function importFolder(packId, folder) {
    const pack = getPack(packId);
    if (!pack) return { ok: false, error: 'Unknown runtime pack.' };
    if (pack.importable === false) return { ok: false, error: `${pack.name} cannot be imported.` };
    if (!fs.existsSync(folder)) return { ok: false, error: 'That folder does not exist.' };
    if (!entryReady(folder, pack)) {
      return { ok: false, error: `That folder is not a ${pack.name} pack. It must contain ${entryNames(pack).join(', ')}.` };
    }
    const stage = stagingDir(dirs, pack.id);
    const extractDir = path.join(stage, 'extract');
    await fsp.rm(stage, { recursive: true, force: true });
    await fsp.mkdir(extractDir, { recursive: true });
    try {
      await fsp.cp(folder, extractDir, { recursive: true, force: true, dereference: true });
      if (!entryReady(extractDir, pack)) throw new Error(`${pack.name} is missing its entry point after copying.`);
      const marker = {
        id: pack.id,
        version: pack.version,
        archive: null,
        entry: pack.entry,
        source: 'import',
        installedAt: Date.now(),
        verifiedAt: Date.now(),
      };
      await fsp.writeFile(path.join(extractDir, MARKER), `${JSON.stringify(marker, null, 2)}\n`, 'utf8');
      const target = runtimeDir(dirs, pack.id);
      if (fs.existsSync(target)) await fsp.rm(target, { recursive: true, force: true });
      await moveAtomic(extractDir, target);
      await fsp.rm(stage, { recursive: true, force: true }).catch(() => {});
      await recordInstall(pack.id, {
        source: 'import',
        installedBytes: pack.installedBytes || 0,
        archive: null,
        error: null,
      });
      return { ok: true, status: status(pack.id) };
    } catch (error) {
      await fsp.rm(stage, { recursive: true, force: true }).catch(() => {});
      return { ok: false, error: error instanceof Error ? error.message : String(error) };
    }
  }

  async function uninstall(packId) {
    const pack = getPack(packId);
    if (!pack) return { ok: false, error: 'Unknown runtime pack.' };
    // Model environments link to the interpreter and uv cache, so prerequisites go last.
    const dependents = getCatalog().packs.filter((item) => (item.requires || []).includes(pack.id) && status(item.id)?.installed);
    if (dependents.length) {
      return { ok: false, error: `${pack.name} is used by ${dependents.map((item) => item.name).join(', ')}. Remove those first.` };
    }
    if (activeDownload?.packId === pack.id) activeDownload.controller.abort();
    await fsp.rm(runtimeDir(dirs, pack.id), { recursive: true, force: true });
    await fsp.rm(stagingDir(dirs, pack.id), { recursive: true, force: true });
    await clearInstall(pack.id);
    return { ok: true, status: status(pack.id) };
  }

  function active() {
    return activeDownload ? { packId: activeDownload.packId } : null;
  }

  return {
    packs: () => getCatalog().packs,
    getPack,
    status,
    statusAll,
    modelRuntime,
    pythonFor,
    sidecarRuntime,
    download,
    cancel,
    verify,
    importFolder,
    uninstall,
    active,
  };
}

