// Generates THIRD_PARTY_NOTICES.md from the installed production dependency tree
// plus the model and runtime catalogs. Run with: npm run notices
//
// The JavaScript section needs `npm ci` first. The catalog sections work without it.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));
const pkg = readJson(path.join(root, 'package.json'));

const LICENSE_FILE = /^(licen[sc]e|copying|notice)(\.|$|-)/i;

function licenseId(meta) {
  if (typeof meta.license === 'string') return meta.license;
  if (meta.license?.type) return meta.license.type;
  if (Array.isArray(meta.licenses)) return meta.licenses.map((l) => l.type || l).join(' OR ');
  return 'UNKNOWN';
}

// Resolve a dependency the way Node does: walk up node_modules folders.
function resolveDir(name, fromDir) {
  let dir = fromDir;
  for (;;) {
    const candidate = path.join(dir, 'node_modules', name);
    if (fs.existsSync(path.join(candidate, 'package.json'))) return candidate;
    const parent = path.dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

function collect() {
  const seen = new Map();
  const queue = Object.keys(pkg.dependencies || {}).map((name) => ({ name, from: root }));
  while (queue.length) {
    const { name, from } = queue.shift();
    const dir = resolveDir(name, from);
    if (!dir) continue;
    const meta = readJson(path.join(dir, 'package.json'));
    const key = `${meta.name}@${meta.version}`;
    if (seen.has(key)) continue;
    const files = fs.readdirSync(dir).filter((f) => LICENSE_FILE.test(f));
    const text = files
      .map((f) => fs.readFileSync(path.join(dir, f), 'utf8').trim())
      .filter(Boolean)
      .join('\n\n');
    seen.set(key, {
      name: meta.name,
      version: meta.version,
      license: licenseId(meta),
      homepage: meta.homepage || meta.repository?.url || '',
      text,
    });
    for (const dep of Object.keys(meta.dependencies || {})) queue.push({ name: dep, from: dir });
    for (const dep of Object.keys(meta.optionalDependencies || {})) queue.push({ name: dep, from: dir });
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
}

const out = [];
out.push('# Third-party notices', '');
out.push(
  'Voxarium is licensed under the GNU Affero General Public License v3.0 or later (see `LICENSE`).',
  'It bundles or downloads the components below, each under its own license.',
  'This file is generated by `npm run notices`; do not edit it by hand.',
  '',
);

// 1. Bundled JavaScript dependencies
out.push('## 1. Bundled JavaScript dependencies', '');
const deps = fs.existsSync(path.join(root, 'node_modules')) ? collect() : [];
if (!deps.length) {
  out.push('_Run `npm ci` and then `npm run notices` to list the bundled JavaScript dependencies._', '');
} else {
  out.push('| Package | Version | License |', '| --- | --- | --- |');
  for (const d of deps) out.push(`| ${d.name} | ${d.version} | ${d.license} |`);
  out.push('');
  const byHash = new Map();
  for (const d of deps) {
    if (!d.text) continue;
    const hash = crypto.createHash('sha256').update(d.text).digest('hex');
    if (!byHash.has(hash)) byHash.set(hash, { text: d.text, names: [] });
    byHash.get(hash).names.push(`${d.name}@${d.version}`);
  }
  out.push('### License texts', '');
  for (const { text, names } of byHash.values()) {
    out.push(`<details><summary>${names.join(', ')}</summary>`, '', '```text', text, '```', '', '</details>', '');
  }
}

// 2. Bundled assets
out.push(
  '## 2. Bundled assets',
  '',
  '| Asset | Source | License |',
  '| --- | --- | --- |',
  '| `public/phonon/*` phonon-tts runtime | https://www.npmjs.com/package/phonon-tts | See section 1 |',
  '| `electron/sidecars/assets/reference-en.wav` | Kokoro `af_heart_0.wav` synthetic sample | Apache-2.0 |',
  '| Voice catalog `src/data/voices.json` | https://huggingface.co/gradium/phonon-voices | **Verify** before release |',
  '',
);

// 3. Downloaded on demand
out.push(
  '## 3. Downloaded on demand (not distributed with Voxarium)',
  '',
  'These are fetched to the user\'s computer from their original hosts, at pinned revisions,',
  'after the user accepts each license in the app. Voxarium does not redistribute them.',
  '',
  '### Models',
  '',
  '| Model | License | Source |',
  '| --- | --- | --- |',
);
const manifests = readJson(path.join(root, 'electron/models/manifests.json'));
for (const m of manifests.models) {
  out.push(`| ${m.name} | ${m.license.id} | https://huggingface.co/${m.repo} |`);
}
out.push('', '### Runtime packs', '', '| Pack | License | Homepage |', '| --- | --- | --- |');
const runtimes = readJson(path.join(root, 'electron/models/runtimes.json'));
for (const r of runtimes.packs) {
  out.push(`| ${r.name} ${r.version || ''} | ${r.license?.id || 'UNKNOWN'} | ${r.homepage || ''} |`);
}
out.push(
  '',
  'Python packages installed into per-model environments (PyTorch, transformers, eSpeak NG and others)',
  'keep their own licenses, which are installed alongside them in the environment.',
  '',
);

fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), out.join('\n'));
console.log(`THIRD_PARTY_NOTICES.md written (${deps.length} JavaScript packages).`);
